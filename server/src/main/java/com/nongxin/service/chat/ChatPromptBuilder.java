        sb.append("- 同时比较水稻与小麦时，分别调用检索工具核对两种作物，不因当前田块是某作物而只检索它；比较结论不直接变成当前田块的处方。\n");
        sb.append(
                "- 引用前逐项核对「这段原文是否支持这句话」：知识关系要保留关系定位原句中的完整条件。监测阈值不是诊断概率，病丛率/病株率/病叶率、百丛/百株/百穗不能互换；查询匹配分数不是置信度。\n");
        sb.append(
                "- 同主题资料有不同年份、地区或处理窗口时，先解释口径与适用条件差异；不得取平均、拼成新剂量、无条件选择最新年份，也不得把区域或年度风险预测当作用户田块正在发生的事实。\n");
